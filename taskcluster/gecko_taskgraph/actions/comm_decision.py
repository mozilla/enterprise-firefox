import logging
import os
import shlex
import subprocess

from taskgraph import create

from gecko_taskgraph import GECKO
from gecko_taskgraph.actions.registry import register_callback_action
from gecko_taskgraph.util.attributes import ENTERPRISE_TRY_PROJECTS
from gecko_taskgraph.util.comm import COMM_PROJECTS, COMM_ROOT
from gecko_taskgraph.util.taskcluster import insert_index

logger = logging.getLogger(__name__)


def is_comm_decision_available(parameters):
    return bool(parameters.get("comm_checkout")) and (
        "comm_head_repository" not in parameters
    )


def comm_decision_command(parameters):
    command = [
        os.path.join(GECKO, "mach"),
        "--log-no-times",
        "taskgraph",
        "decision",
        f"--root={os.path.relpath(COMM_ROOT, GECKO)}",
        f"--project={COMM_PROJECTS[parameters['project']]}",
        f"--owner={parameters['owner']}",
        f"--level={parameters['level']}",
        f"--tasks-for={parameters['tasks_for']}",
        f"--repository-type={parameters['repository_type']}",
        f"--pushlog-id={parameters['pushlog_id']}",
        f"--pushdate={parameters['pushdate']}",
        f"--base-repository={parameters['base_repository']}",
        f"--base-rev={parameters['base_rev']}",
        f"--head-repository={parameters['head_repository']}",
        f"--head-ref={parameters['head_ref']}",
        f"--head-rev={parameters['head_rev']}",
    ]
    if parameters.get("base_ref"):
        command.append(f"--base-ref={parameters['base_ref']}")
    if parameters["project"] in ENTERPRISE_TRY_PROJECTS:
        # Picks up the try_task_config.json of the Gecko checkout.
        command.append("--allow-parameter-override")
    return command


def comm_decision_index_paths(parameters, graph_config):
    trust_domain = graph_config["trust-domain"]
    project = parameters["project"]
    rev = parameters["head_rev"]
    if parameters["tasks_for"].startswith("github-pull-request"):
        return [
            f"{trust_domain}.v2.{project}-pr.revision.{rev}.taskgraph.comm-decision"
        ]
    branch = parameters["head_ref"].removeprefix("refs/heads/")
    return [
        f"{trust_domain}.v2.{project}.branch.{branch}.latest.taskgraph.comm-decision",
        f"{trust_domain}.v2.{project}.revision.{rev}.taskgraph.comm-decision",
    ]


@register_callback_action(
    name="comm-decision",
    title="Thunderbird Decision",
    symbol="DC",
    description=(
        "Generate the Enterprise Thunderbird task graph for this push. "
        "Its tasks are created in the task group of this action, which "
        "provides the actions for them."
    ),
    order=1100,
    context=[],
    available=is_comm_decision_available,
    # Not `generic`: the graph contains signing tasks, so the hook role needs
    # the scopes of the branch rather than those of the generic actions.
    # WIP - HACK FOR TRY: use the existing generic hooks.
    permission="generic",
    comm_checkout=True,
)
def comm_decision_action(parameters, graph_config, input, task_group_id, task_id):
    # A process can only register a single graph config, so the Thunderbird
    # graph is generated by its own `mach taskgraph decision`, which reads the
    # comm repository from the COMM_* variables. TASK_ID is inherited, so its
    # tasks are created in the task group of this action.
    env = dict(os.environ)
    for key, value in parameters["comm_checkout"].items():
        env[f"COMM_{key.upper()}"] = value
    if pr_number := parameters.get("pull_request_number"):
        env["GECKO_PULL_REQUEST_NUMBER"] = str(pr_number)

    command = comm_decision_command(parameters)
    logger.info(f"Running {shlex.join(command)}")
    # WIP - HACK FOR TRY: COMM_DECISION_DRY_RUN generates the graph and its
    # artifacts without creating any task, from the comm-decision-thunderbird
    # task, until a decision task is allowed to trigger the hook.
    dry_run = os.environ.get("COMM_DECISION_DRY_RUN")
    if create.testing and not dry_run:
        return
    if dry_run:
        env["TASKGRAPH_DRY_RUN"] = "1"
        with open(os.path.join(GECKO, "artifacts", "created-tasks.log"), "w") as fh:
            subprocess.run(command, env=env, cwd=GECKO, check=True, stdout=fh)
        return
    for index_path in comm_decision_index_paths(parameters, graph_config):
        insert_index(index_path, os.environ["TASK_ID"])
    subprocess.run(command, env=env, cwd=GECKO, check=True)
